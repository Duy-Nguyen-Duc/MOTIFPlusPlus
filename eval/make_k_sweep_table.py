"""Collect the K-shot sweep into docs/table_k_sweep.tex (+ a markdown print).

Rows per K: the F1 reference sweep (cross_emb_2, all-pairs evaluation, the six transfer pairs read out),
MOTIF (K=5 reference only), ours (graph-hard + E-LoRA + geometry-token depth) and ours + perception
steering, then the same two with the motion-aware graph (docs/15, eval_results/abl_tgraph_k<K>{,_cp_300}).
Missing runs print as "--"; re-run whenever a SUMMARY.json lands.

    python eval/make_k_sweep_table.py [--out docs/table_k_sweep.tex]
"""
import argparse
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
F1_SWEEP = Path("/pfss/mlde/workspaces/mlde_wsp_IAS_SAMMerge/cross_emb_2/NewTest/MOTIF/eval_results/f1_k_sweep")
PAIRS = [("panda_wristcam", "PushCube-v1"), ("panda_wristcam", "PlaceSphere-v1"),
         ("xarm6_robotiq_wristcam", "PullCube-v1"), ("xarm6_robotiq_wristcam", "LiftPegUpright-v1"),
         ("widowxai_wristcam", "PickCube-v1"), ("widowxai_wristcam", "StackCube-v1")]
KS = [1, 3, 5, 10, 50]
MOTIF_K5 = [45, 17, 44, 23, 44, 2]          # MOTIF seed-42 reference, Table-1 protocol


def ours(k, steer, tgraph=False):
    base = f"abl_tgraph_k{k}" if tgraph else "graph_hard_elora_geod" if k == 5 else f"graph_hard_elora_geod_k{k}"
    name = base + ("_percept_cp_300" if (steer and k == 5 and not tgraph) else "_cp_300" if steer else "")
    p = REPO / "eval_results" / name / "SUMMARY.json"
    if not p.exists():
        return None
    d = json.load(open(p))
    by = {(r["robot"], r["task"]): r["successes"] for r in d["rows"]}
    return [by[pr] for pr in PAIRS]


def f1(k):
    d = F1_SWEEP / f"K{k}"
    if not d.exists():
        return None
    out = []
    for robot, task in PAIRS:
        p = d / f"{robot}__{task}.json"
        if not p.exists():
            return None
        out.append(json.load(open(p))["successes"])
    return out


def fmt(v):
    return "--" if v is None else [f"{2 * x:.1f}" for x in v] + [f"{sum(v) / 3:.1f}"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=REPO / "docs/table_k_sweep.tex")
    args = ap.parse_args()
    rows = []                                    # (K, label, counts or None)
    for k in KS:
        rows.append((k, "F1 (reference sweep)", f1(k)))
        if k == 5:
            rows.append((k, "MOTIF~\\cite{motif}", MOTIF_K5))
        rows.append((k, "Ours (E-LoRA + geometry tokens)", ours(k, False)))
        rows.append((k, "Ours + perception steering", ours(k, True)))
        rows.append((k, "Ours, motion-aware graph", ours(k, False, tgraph=True)))
        rows.append((k, "Ours, motion-aware graph + perception steering", ours(k, True, tgraph=True)))
    md = ["| K | method | Push | Sphere | Pull | Peg | Pick | Stack | total/300 | % |", "|---|---|---|---|---|---|---|---|---|---|"]
    tex = []
    last_k = None
    for k, label, v in rows:
        plain = label.replace("~\\cite{motif}", "")
        if v is None:
            md.append(f"| {k} | {plain} | -- | -- | -- | -- | -- | -- | -- | -- |")
            cells = ["--"] * 7
        else:
            counts = " | ".join(map(str, v))
            md.append(f"| {k} | {plain} | {counts} | {sum(v)} | {sum(v) / 3:.1f} |")
            cells = fmt(v)
        if last_k is not None and k != last_k:
            tex.append("\\midrule")
        kcell = f"$K={k}$" if k != last_k else ""
        tex.append(f"{kcell} & {label} & {' & '.join(cells)} \\\\")
        last_k = k
    body = "\n".join(tex)
    doc = f"""% K-shot sweep, Table-1 protocol: 6 transfer pairs x 50 episodes (300 total), seeds 2025-2074, policy seed 7.
% Generated by eval/make_k_sweep_table.py from eval_results/*/SUMMARY.json and the F1 reference sweep
% (cross_emb_2/NewTest/MOTIF/eval_results/f1_k_sweep/K*). "--" = run not finished yet. Requires booktabs.
\\begin{{table}}[t]
\\centering
\\small
\\setlength{{\\tabcolsep}}{{3.5pt}}
\\begin{{tabular}}{{l l cc cc cc c}}
\\toprule
& & \\multicolumn{{2}}{{c}}{{Panda}} & \\multicolumn{{2}}{{c}}{{xArm6}} & \\multicolumn{{2}}{{c}}{{WidowX AI}} & \\\\
\\cmidrule(lr){{3-4}} \\cmidrule(lr){{5-6}} \\cmidrule(lr){{7-8}}
Shots & Method & PushCube & PlaceSphere & PullCube & LiftPegUpright & PickCube & StackCube & Avg. \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\caption{{Few-shot transfer success rate (\\%) as a function of the number $K$ of target demonstrations, 50 episodes per robot--task pair; Avg.\\ is over all 300 episodes. Perception steering is applied at test time to the checkpoint of the row above, without retraining. The motion-aware graph rows retrain all three stages with the joint trajectories on the nodes and edges of the tokenizer's kinematic graph.}}
\\label{{tab:k_sweep}}
\\end{{table}}
"""
    args.out.write_text(doc)
    print("\n".join(md))
    print(f"\nwrote {args.out}")


if __name__ == "__main__":
    main()
