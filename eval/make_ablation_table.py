"""K=5 ablations of the 249/300 system (graph-routed E-LoRA + geometry tokens + perception steering) ->
docs/table_ablation.tex (+ a markdown print). One component removed per row pair (policy alone / + steering):
no kinematic graph (learned per-robot vector), no primitive labels (task + episode-progress alignment as MOTIF),
no geometry tokens (the E-LoRA checkpoint). The last two row pairs are graph variants, not removals: the motion-aware
graph (joint trajectories on nodes and edges, docs/15) and the same with joint-attentive routing. Missing runs print as
"--"; re-run whenever a SUMMARY.json lands.

    python eval/make_ablation_table.py [--out docs/table_ablation.tex]
"""
import argparse
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
PAIRS = [("panda_wristcam", "PushCube-v1"), ("panda_wristcam", "PlaceSphere-v1"),
         ("xarm6_robotiq_wristcam", "PullCube-v1"), ("xarm6_robotiq_wristcam", "LiftPegUpright-v1"),
         ("widowxai_wristcam", "PickCube-v1"), ("widowxai_wristcam", "StackCube-v1")]
# label, (plain run, steered run)
ROWS = [("Full: graph routing + primitive labels + E-LoRA + geometry tokens",
         ("graph_hard_elora_geod", "graph_hard_elora_geod_percept_cp_300")),
        ("w/o kinematic graph (learned embodiment vector $h_r$)", ("abl_nograph_k5", "abl_nograph_k5_cp_300")),
        ("w/o primitive labels (task + episode progress, as MOTIF)", ("abl_noprim_k5", "abl_noprim_k5_cp_300")),
        ("w/o geometry tokens", ("graph_hard_elora", "graph_hard_elora_percept_cp_300")),
        ("Motion-aware graph (joint trajectories on nodes and edges)", ("abl_tgraph_k5", "abl_tgraph_k5_cp_300")),
        ("Motion-aware graph + joint-attentive routing", ("abl_tgraph_attn_k5", "abl_tgraph_attn_k5_cp_300"))]


def counts(name):
    p = REPO / "eval_results" / name / "SUMMARY.json"
    if not p.exists():
        return None
    by = {(r["robot"], r["task"]): r["successes"] for r in json.load(open(p))["rows"]}
    return [by[pr] for pr in PAIRS]


def cells(v):
    return ["--"] * 7 if v is None else [f"{2 * x:.1f}" for x in v] + [f"{sum(v) / 3:.1f}"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=REPO / "docs/table_ablation.tex")
    args = ap.parse_args()
    md = ["| variant | steering | Push | Sphere | Pull | Peg | Pick | Stack | total/300 | % |", "|---|---|---|---|---|---|---|---|---|---|"]
    tex = []
    for i, (label, (plain, steered)) in enumerate(ROWS):
        if i:
            tex.append("\\midrule")
        for steer, name in ((False, plain), (True, steered)):
            v = counts(name)
            md.append(f"| {label if not steer else ''} | {'yes' if steer else 'no'} | "
                      + (" | ".join(map(str, v)) + f" | {sum(v)} | {sum(v) / 3:.1f} |" if v else "-- | -- | -- | -- | -- | -- | -- | -- |"))
            row = "\\quad + perception steering" if steer else label
            tex.append(f"{row} & {' & '.join(cells(v))} \\\\")
    body = "\n".join(tex)
    doc = f"""% K=5 ablations of the 249/300 system, Table-1 protocol: 6 transfer pairs x 50 episodes, seeds 2025-2074, policy seed 7.
% Generated by eval/make_ablation_table.py from eval_results/<run>/SUMMARY.json; "--" = run not finished yet. Requires booktabs.
% Runs: full = graph_hard_elora_geod; w/o graph = abl_nograph_k5 (models.stage1.morphology=embed, stages 1-3 retrained);
% w/o primitive labels = abl_noprim_k5 (prim_conditioning=false infonce_cond=task infonce_sigma=0.02, stages 1-3 retrained);
% w/o geometry tokens = graph_hard_elora (same stages 1-2, stage 3 without geometry_cfg);
% motion-aware graph = abl_tgraph_k5 (models.stage1.graph_temporal=true, dataset_maniskill_prim_q, stages 1-3 retrained);
% + joint-attentive routing = abl_tgraph_attn_k5 (also models.stage1.graph_routing=attn). Steered rows: same checkpoint, colour/plane, k=1, r=0.30.
\\begin{{table}}[t]
\\centering
\\small
\\setlength{{\\tabcolsep}}{{3.5pt}}
\\begin{{tabular}}{{l cc cc cc c}}
\\toprule
& \\multicolumn{{2}}{{c}}{{Panda}} & \\multicolumn{{2}}{{c}}{{xArm6}} & \\multicolumn{{2}}{{c}}{{WidowX AI}} & \\\\
\\cmidrule(lr){{2-3}} \\cmidrule(lr){{4-5}} \\cmidrule(lr){{6-7}}
Variant & PushCube & PlaceSphere & PullCube & LiftPegUpright & PickCube & StackCube & Avg. \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\caption{{Ablations at $K=5$ (success rate in \\%, 50 episodes per pair; Avg.\\ over all 300 episodes). Each of the first three variants removes one component of the full system and retrains the affected stages: the kinematic graph is replaced by a learned vector per robot (routing query, decoder bias and one E-LoRA factor per robot instead of per joint); the rule-based primitive labels are replaced by the task instruction and episode progress in the InfoNCE and adversarial alignment, as in MOTIF; the geometry tokens are removed from the stage-3 policy. The last two variants change the graph instead: the motion-aware graph encodes the joint trajectories of the window on the nodes and edges of the kinematic graph when the tokenizer is trained, and joint-attentive routing lets every motion token attend over the joint nodes instead of using the pooled graph vector; all stages are retrained and the policy still never reads joint positions. Perception steering is applied at test time to the checkpoint of the row above.}}
\\label{{tab:ablation}}
\\end{{table}}
"""
    args.out.write_text(doc)
    print("\n".join(md))
    print(f"\nwrote {args.out}")


if __name__ == "__main__":
    main()
